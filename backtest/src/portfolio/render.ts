// Markdown for results/portfolio.md. Wording follows docs/SPEC.md section 8.
import { CALM_ID } from '../config.ts';
import { GRID } from '../grid.ts';
import type { BreakEvenRow, ErrorStats, PairSetRow, PopulationRow, Portfolio } from './report.ts';

const usd = (x: number): string => {
  const abs = Math.abs(x);
  if (abs >= 1e6) return `$${(x / 1e6).toFixed(2)}M`;
  if (abs >= 1e3) return `$${(x / 1e3).toFixed(1)}k`;
  return `$${x.toFixed(0)}`;
};
const pct = (part: number, whole: number, digits = 1): string => (whole === 0 ? 'n/a' : `${((part / whole) * 100).toFixed(digits)}%`);
const share = (x: number, digits = 1): string => (Number.isFinite(x) ? `${(x * 100).toFixed(digits)}%` : 'n/a');
const err = (x: number): string => (Number.isFinite(x) ? `${(x * 100).toFixed(3)}%` : 'n/a');
const times = (x: number): string => (!Number.isFinite(x) ? 'never' : x >= 100 ? x.toFixed(0) : x.toFixed(1));

function table(headers: string[], rows: Array<Array<string | number>>): string {
  const lines = [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`];
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  return lines.join('\n');
}

const R = (r: number): string => `${Math.round(r * 100)}%`;

export function renderPortfolio(p: Portfolio): string {
  const label = (period: string): string => p.periods.find((x) => x.period === period)!.label;
  const crashes = p.periods.filter((x) => x.period !== CALM_ID).map((x) => x.period);
  const all = (rows: PopulationRow[], period: string, trigger: number, reserveShare: number): PopulationRow =>
    rows.find((r) => r.period === period && r.chain === 'all' && r.trigger === trigger && r.reserveShare === reserveShare)!;
  const base = p.base;
  const out: string[] = [];

  out.push('# Levee backtest: the whole population, a shared reserve, a calm period and carry');
  out.push('');
  out.push('Generated by `pnpm backtest` from the committed files in `backtest/data/derived`. The method is in `backtest/README.md`, under "Method: population, shared reserve, calm period and carry", which was committed before any of these results were computed.');
  out.push('');
  out.push('**Read this first.**');
  out.push('');
  out.push('- Every saved position is a simulation result, under the same assumptions as `summary.md`: the keeper, RPCs, NEAR and the MPC network all work, with a fixed delay D.');
  out.push('- The population is every address with native USDC variable debt on the Aave v3 Pools on Base and Arbitrum, liquidated or not. Liquidated positions in the headline set keep their headline paths. Every other path is rebuilt from portfolio reads, actions and oracle prices; its error is in Validation below.');
  out.push('- A member that was not liquidated in reality counts as surviving, with or without Levee. What Levee changes for it is only how much reserve it draws.');
  out.push('- Hyperliquid is not in these numbers. Its only source here holds liquidation fills, with no account states over time.');
  out.push('- No crash frequency is estimated from two windows. Carry is set against each crash as a break-even.');
  out.push('');
  out.push(`Unless stated: T ${base.trigger.toFixed(2)}, G ${base.target.toFixed(2)}, R ${R(base.reserveShare)} of debt at arming, D ${base.delaySec} s, cooldown 60 s.`);
  out.push('');

  // Upfront against Levee.
  out.push('## Levee against the same USDC repaid upfront');
  out.push('');
  out.push('Every member holds a reserve of R × its debt at arming. "Upfront" repays that amount at arming instead, with no keeper. Saved counts liquidated members only, because every other member survived either way. Carry is what holding the reserve idle cost over the period against repaying it, at the period\'s USDC borrow APR.');
  out.push('');
  out.push('The pre-registered rule, like the headline model, takes a landed repay off total debt for good. Upfront counts a repay only up to the USDC debt still on the path, so a borrower that later repaid its USDC itself gets no double credit. The "capped" column gives Levee the same treatment. Where Levee beats upfront, it is that double credit.');
  out.push('');
  const carryFor = (period: string): number =>
    (['arbitrum', 'base'] as const).reduce((sum, chain) => {
      const row = p.population.find((r) => r.period === period && r.chain === chain && r.trigger === base.trigger && r.reserveShare === base.reserveShare)!;
      const rate = p.carryByPeriod.find((c) => c.span === period && c.chain === chain)!;
      const days = p.periods.find((x) => x.period === period)!.days;
      return sum + row.reserveHeld * rate.borrowApr * (days / 365);
    }, 0);
  out.push(
    table(
      ['Period', 'Members', 'Liquidated', 'Saved: Levee', 'Levee, repay capped at USDC debt', 'Saved: upfront', 'Bonus at risk', 'Avoided: Levee', 'Avoided: upfront', 'Reserve held', 'Drawn by Levee', 'Of that, by members that survived anyway', 'Carry over the period'],
      p.periods.map((x) => {
        const r = all(p.population, x.period, base.trigger, base.reserveShare);
        return [
          label(x.period),
          r.members,
          r.liquidated,
          `${r.savedLevee} (${pct(r.savedLevee, r.liquidated)})`,
          r.savedLeveeCapped,
          `${r.savedUpfront} (${pct(r.savedUpfront, r.liquidated)})`,
          usd(r.bonusAtRisk),
          usd(r.bonusAvoidedLevee),
          usd(r.bonusAvoidedUpfront),
          usd(r.reserveHeld),
          `${usd(r.drawn)} (${pct(r.drawn, r.reserveHeld)})`,
          `${usd(r.drawnBySurvivors)} (${pct(r.drawnBySurvivors, r.drawn)})`,
          usd(carryFor(x.period)),
        ];
      }),
    ),
  );
  out.push('');

  // Periods.
  out.push('## Periods and population');
  out.push('');
  out.push(
    `The calm period follows the rule in the README: the longest run of days with no daily move in the Base AaveOracle WETH price over 8%, from 2025-01-01 to 2026-11-01, was ${p.calm.runDays} days from ${new Date(p.calm.runStartTime * 1000).toISOString().slice(0, 10)}. The 30 days at its centre are used. The largest daily move inside them was ${share(p.calm.largestMove)}.`,
  );
  out.push('');
  out.push(
    table(
      ['Period', 'Days', 'Chain', 'Blocks', 'Members at start', 'Joined during', 'Armed', 'USDC debt at start'],
      p.periods.flatMap((x) => x.chains.map((c) => [label(x.period), x.days, c.chain, `${c.fromBlock} to ${c.toBlock}`, c.startMembers, c.newcomers, c.armed, usd(c.usdcDebtAtStart)])),
    ),
  );
  out.push('');
  out.push('"Armed" leaves out accounts that joined with a USDC borrow and repaid it before any read saw the debt.');
  out.push('');

  // Triggers.
  out.push('## How often triggers fire, and where the reserve goes');
  out.push('');
  out.push('Per trigger, at R 30%. "Crossed T" counts members armed above T whose HF later fell below T. Of those: liquidated in the period (needed), HF below 1 on the path but not liquidated (a path error or a position too small to liquidate), and the rest, which recovered on their own (false alarms). "Drawn" is reserve sent by the keeper. "By survivors" is the part sent to members that were not liquidated in reality.');
  out.push('');
  for (const x of p.periods) {
    out.push(`### ${label(x.period)}`);
    out.push('');
    out.push(
      table(
        ['T', 'Chain', 'Members', 'Armed below T', 'Crossed T', 'Liquidated', 'HF below 1, not liquidated', 'False alarms', 'Reserve held', 'Drawn', 'Drawn, members armed above T', 'By survivors', 'Saved: Levee', 'Saved: upfront'],
        p.population
          .filter((r) => r.period === x.period)
          .map((r) => [
            r.trigger.toFixed(2),
            r.chain,
            r.members,
            r.armedBelow,
            r.crossed,
            r.crossedLiquidated,
            r.crossedBelow1,
            `${r.falseAlarms} (${pct(r.falseAlarms, r.crossed)})`,
            usd(r.reserveHeld),
            `${usd(r.drawn)} (${pct(r.drawn, r.reserveHeld)})`,
            `${usd(r.drawn - r.drawnArmedBelow)} (${pct(r.drawn - r.drawnArmedBelow, r.reserveHeld - r.reserveHeldArmedBelow)})`,
            `${usd(r.drawnBySurvivors)} (${pct(r.drawnBySurvivors, r.drawn)})`,
            `${r.savedLevee} of ${r.liquidated}`,
            `${r.savedUpfront} of ${r.liquidated}`,
          ]),
      ),
    );
    out.push('');
  }
  out.push('Members armed below T fire at once, which is an upfront repay. Their draw is inside "Drawn". "Drawn, members armed above T" leaves them out, against the reserve those members held: it is the share a trigger set below current HF actually spends.');
  out.push('');

  out.push('## Reserve size');
  out.push('');
  out.push(`T ${base.trigger.toFixed(2)}, every member, both chains.`);
  out.push('');
  out.push(
    table(
      ['Period', 'R', 'Reserve held', 'Drawn', 'By survivors', 'Saved: Levee', 'Saved: upfront', 'Avoided: Levee', 'Avoided: upfront'],
      p.populationByReserve
        .filter((r) => r.chain === 'all')
        .map((r) => [
          label(r.period),
          R(r.reserveShare),
          usd(r.reserveHeld),
          `${usd(r.drawn)} (${pct(r.drawn, r.reserveHeld)})`,
          `${usd(r.drawnBySurvivors)} (${pct(r.drawnBySurvivors, r.drawn)})`,
          `${r.savedLevee} of ${r.liquidated}`,
          `${r.savedUpfront} of ${r.liquidated}`,
          usd(r.bonusAvoidedLevee),
          usd(r.bonusAvoidedUpfront),
        ]),
    ),
  );
  out.push('');

  out.push('## By size');
  out.push('');
  out.push('Debt at arming. T 1.20, R 30%, both chains. Most members are small, and most dust positions with HF below 1 are never liquidated, because it would not pay.');
  out.push('');
  out.push(
    table(
      ['Period', 'Debt at arming', 'Members', 'Armed below T', 'Crossed T', 'Liquidated', 'HF below 1, not liquidated', 'False alarms', 'Reserve held', 'Drawn', 'By survivors'],
      p.bySize.map((r) => [label(r.period), r.bucket, r.members, r.armedBelow, r.crossed, r.liquidated, r.crossedBelow1, r.falseAlarms, usd(r.reserveHeld), usd(r.drawn), usd(r.drawnBySurvivors)]),
    ),
  );
  out.push('');

  // Calm per member.
  const calm = p.periods.find((x) => x.period === CALM_ID)!;
  out.push('## The calm period, per member per 30 days');
  out.push('');
  out.push(`${calm.label}. Members armed above T only, so a repay at arming does not count as a trigger firing. A newcomer is counted for the part of the 30 days after it joined.`);
  out.push('');
  out.push(
    table(
      ['T', 'Members armed above T', 'Crossed T', 'Per member per 30 days', 'Of those, liquidated', 'Reserve drawn per member', 'Reserve held by them', 'Drawn as share of it'],
      GRID.triggers.map((t) => {
        const r = all(p.population, CALM_ID, t, base.reserveShare);
        const above = r.members - r.armedBelow;
        const drawnAbove = r.drawn - r.drawnArmedBelow;
        const heldAbove = r.reserveHeld - r.reserveHeldArmedBelow;
        return [t.toFixed(2), above, r.crossed, (r.crossed / Math.max(1, above)).toFixed(3), r.crossedLiquidated, usd(drawnAbove / Math.max(1, above)), usd(heldAbove), pct(drawnAbove, heldAbove, 2)];
      }),
    ),
  );
  out.push('');

  // Pairs.
  out.push('## One reserve shared across two positions');
  out.push('');
  out.push('Real pairs are addresses with native USDC debt on both Base and Arbitrum at a period start.');
  out.push('');
  out.push(
    table(
      ['Period', 'Real pairs', 'With a liquidated position', 'Both liquidated', 'Synthetic pairs added'],
      p.realPairs.map((r) => [label(r.period), r.pairs, r.withLiquidation, r.bothLiquidated, r.period === CALM_ID ? 'no, not a crash' : r.syntheticAdded ? 'yes' : 'no']),
    ),
  );
  out.push('');
  out.push(
    `Budget B = R × both debts at arming. (a) Shared: one Levee reserve B, first come, first served, at D ${base.delaySec} s and at D ${p.sharedSlowDelaySec} s; sharing across chains needs the off-venue reserve, whose route time is not measured. (b) Upfront: B repaid at arming, split by debt. (c) Separate: two Levee reserves, split by debt, at D ${base.delaySec} s. Saved counts liquidated positions; every other position survives under all three.`,
  );
  out.push('');
  for (const period of crashes) {
    for (const set of ['real', 'synthetic, independent', 'synthetic, both liquidated'] as const) {
      const rows = p.pairs.filter((r) => r.period === period && r.set === set);
      if (rows.length === 0) continue;
      const first = rows[0]!;
      out.push(`### ${label(period)}, ${set} pairs`);
      out.push('');
      out.push(
        `${first.pairs} pairs, ${first.pairsWithLiquidation} with a liquidated position, ${first.pairsBothLiquidated} with both liquidated, ${first.liquidatedPositions} liquidated positions in all.` +
          (set === 'real' ? '' : ` ${first.skippedAnchors} anchors had no partner in the debt range and were skipped.`),
      );
      out.push('');
      out.push(pairTable(rows));
      out.push('');
    }
  }

  // Carry.
  out.push('## Carry');
  out.push('');
  out.push('Aave USDC rates on each Pool, as APR. Today the reserve sits idle as USDC with the rescuer, so against an upfront repay it costs the borrow APR. The "earning" column is a hypothetical, not in the spec: a reserve that earns the USDC supply APR costs the difference.');
  out.push('');
  out.push(
    table(
      ['Chain', 'Span', 'Days', 'Borrow APR', 'Supply APR', 'Idle reserve, per $1,000 a year', 'Earning reserve (hypothetical), per $1,000 a year'],
      [...p.carry, ...p.carryByPeriod].map((c) => [c.chain, c.span === CALM_ID ? `calm, ${calm.label}` : p.periods.find((x) => x.period === c.span)?.label ?? c.span, c.days, share(c.borrowApr, 2), share(c.supplyApr, 2), usd(c.idlePer1000), usd(c.earningPer1000)]),
    ),
  );
  out.push('');
  out.push('### Break-even against one crash');
  out.push('');
  out.push('Bonus avoided in each crash per $1,000 of reserve held across the whole population, against a year of carry at the 2025-01-01 to 2026-11-01 mean rate, weighted by reserve held per chain. "Crashes a year to pay" is how many crashes like this one a year would make the bonus Levee avoided equal the interest an upfront repay would have saved. It sets Levee against a reserve that does nothing. Against an upfront repay of the same size there is no break-even for one position: upfront avoided as much bonus as Levee with its repay capped at the USDC debt left, in every row, and costs no carry. Where uncapped Levee is ahead of upfront, the gap is the double credit described at the top.');
  out.push('');
  out.push(breakEvenTable(p.breakEven.filter((b) => b.chain === 'all'), label));
  out.push('');
  const sharedRows = p.sharedBreakEven.filter((s) => s.reserveShare === base.reserveShare);
  if (sharedRows.length > 0) {
    out.push('### Break-even for a shared reserve');
    out.push('');
    out.push('Bonus avoided by one shared reserve (D 60 s) beyond the same budget repaid upfront, per $1,000 of budget, against a year of carry on the budget at the mean borrow APR of both chains. R 30%.');
    out.push('');
    out.push(
      table(
        ['Window', 'Pairs', 'Budget', 'Extra bonus avoided by sharing', 'Per $1,000 of budget', 'Crashes a year to pay'],
        sharedRows.map((s) => [label(s.period), s.set, usd(s.budget), usd(s.extraBonusShared), usd(s.extraPerDollar * 1000), times(s.crashesToPayIdle)]),
      ),
    );
    out.push('');
  }

  // Validation.
  out.push('## Validation');
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', 'Candidates', 'Members at start', 'Sum of member balances against totalSupply'],
      p.validation.map((v) => [label(v.period), v.chain, v.candidates, v.startMembers, v.totalSupplyGap === 0 ? 'equal' : `short by ${(v.totalSupplyGap * 100).toFixed(6)}%`]),
    ),
  );
  out.push('');
  out.push('Rebuilt HF against `getUserAccountData`, as |rebuilt / direct - 1|, over reads with at least $1 of debt and HF below 10. Below $1, Aave rounds values to 8 decimals of USD, which moves a dust position\'s HF by whole percents.');
  out.push('');
  const statCells = (s: ErrorStats | null): Array<string | number> => (s ? [s.n, err(s.median), err(s.p95), err(s.p99), err(s.max), share(s.within05)] : ['n/a', '', '', '', '', '']);
  out.push(
    table(
      ['Period', 'Chain', 'Check', 'n', 'Median', 'p95', 'p99', 'Max', 'Within 0.5%'],
      p.validation.flatMap((v) => [
        [label(v.period), v.chain, 'At every read block, with the state just read', ...statCells(v.readback)],
        [label(v.period), v.chain, 'Same, dust included', ...statCells(v.readbackAll)],
        [label(v.period), v.chain, 'Sample: random members at random blocks', ...statCells(v.sampleRandom)],
        [label(v.period), v.chain, 'Sample: members rebuilt at HF 1.0 to 1.4', ...statCells(v.sampleNear)],
        ...(v.headline ? [[label(v.period), v.chain, 'Headline positions, at every committed direct read', ...statCells(v.headline)]] : []),
      ]),
    ),
  );
  out.push('');
  out.push('The read-block check tests prices, thresholds, eMode and interest. The sample also tests the re-read grid, because between an action and the next grid point the old state stands. Agreement on which side of each trigger HF sits, over the whole sample:');
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', ...GRID.triggers.map((t) => `T ${t.toFixed(2)}`)],
      p.validation.map((v) => [label(v.period), v.chain, ...GRID.triggers.map((t) => share(v.sampleAgreement[String(t)] ?? NaN))]),
    ),
  );
  out.push('');
  return out.join('\n');
}

function pairTable(rows: PairSetRow[]): string {
  return table(
    ['R', 'Liquidated saved: shared, D 60 s', 'Shared, D 300 s', 'Upfront split', 'Separate', 'Both saved: shared', 'Upfront', 'Separate', 'Bonus avoided: shared', 'Upfront', 'Separate', 'Shared reserve sent to survivors'],
    rows.map((r) => [
      R(r.reserveShare),
      `${r.savedLiquidated.shared} of ${r.liquidatedPositions}`,
      r.savedLiquidated.sharedSlow,
      r.savedLiquidated.upfront,
      r.savedLiquidated.separate,
      r.bothSaved.shared,
      r.bothSaved.upfront,
      r.bothSaved.separate,
      usd(r.bonusAvoided.shared),
      usd(r.bonusAvoided.upfront),
      usd(r.bonusAvoided.separate),
      `${usd(r.sharedDrawnBySurvivors)} of ${usd(r.sharedDrawn)}`,
    ]),
  );
}

function breakEvenTable(rows: BreakEvenRow[], label: (period: string) => string): string {
  return table(
    ['Window', 'R', 'Reserve held', 'Bonus avoided: Levee', 'Levee, capped', 'Upfront', 'Levee, per $1,000 held', 'Upfront, per $1,000', 'Idle carry per $1,000 a year', 'Crashes a year to pay', 'Earning carry (hypothetical)', 'Crashes a year to pay'],
    rows.map((b) => [
      label(b.period),
      R(b.reserveShare),
      usd(b.reserveHeld),
      usd(b.bonusAvoidedLevee),
      usd(b.bonusAvoidedLeveeCapped),
      usd(b.bonusAvoidedUpfront),
      `$${(b.perDollarLevee * 1000).toFixed(2)}`,
      `$${(b.perDollarUpfront * 1000).toFixed(2)}`,
      `$${(b.carryIdle * 1000).toFixed(2)}`,
      times(b.crashesToPayIdle),
      `$${(b.carryEarning * 1000).toFixed(2)}`,
      times(b.crashesToPayEarning),
    ]),
  );
}
