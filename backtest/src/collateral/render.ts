// Markdown for results/collateral.md. Wording follows docs/SPEC.md section 8.
import { CALM_ID } from '../config.ts';
import { GRID } from '../grid.ts';
import { REASONS, type CollateralReport, type GridRow, type PopulationRow, type Totals } from './report.ts';

const usd = (x: number): string => {
  const abs = Math.abs(x);
  const sign = x < 0 ? '-' : '';
  if (abs >= 1e6) return `${sign}$${(abs / 1e6).toFixed(2)}M`;
  if (abs >= 1e3) return `${sign}$${(abs / 1e3).toFixed(1)}k`;
  if (abs >= 10) return `${sign}$${abs.toFixed(0)}`;
  return `${sign}$${abs.toFixed(2)}`;
};
const pct = (part: number, whole: number, digits = 1): string => (whole === 0 ? 'n/a' : `${((part / whole) * 100).toFixed(digits)}%`);
const share = (x: number, digits = 1): string => (Number.isFinite(x) ? `${(x * 100).toFixed(digits)}%` : 'n/a');
const bps = (x: number): string => (Number.isFinite(x) ? x.toFixed(1) : 'n/a');
const per1000 = (amount: number, debt: number): string => (debt > 0 ? `$${((amount / debt) * 1000).toFixed(2)}` : 'n/a');

function table(headers: string[], rows: Array<Array<string | number>>): string {
  const lines = [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`];
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  return lines.join('\n');
}

const reverted = (t: Totals): number => t.revertedCap + t.revertedLiquidity;

export function renderCollateral(r: CollateralReport): string {
  const label = (period: string): string => r.periods.find((p) => p.period === period)!.label;
  const periods = r.periods.map((p) => p.period);
  const crashes = periods.filter((p) => p !== CALM_ID);
  const row = (period: string, trigger: number, slippageBps: number, tier: 'cheapest' | 'configured' = 'cheapest', chain = 'all'): PopulationRow =>
    r.population.find((x) => x.period === period && x.chain === chain && x.trigger === trigger && x.slippageBps === slippageBps && x.tier === tier)!;
  const cmp = (period: string, trigger: number) => r.comparison.find((c) => c.period === period && c.trigger === trigger)!;
  const gridRow = (window: string, trigger: number, target: number, delaySec: number, slippageBps: number, cooldownSec = 60): GridRow | undefined =>
    r.grid.find((g) => g.window === window && g.trigger === trigger && g.target === target && g.delaySec === delaySec && g.slippageBps === slippageBps && g.cooldownSec === cooldownSec);
  const b = r.base;
  const caps = r.rules.slippageBps;
  const out: string[] = [];

  out.push('# Levee backtest: repay from collateral');
  out.push('');
  out.push('Generated by `pnpm backtest` from the committed files in `backtest/data/derived`. The method is in `backtest/README.md`, under "Method: repay from collateral", which was committed before any collateral-mode code existed or any of these results were computed.');
  out.push('');
  out.push('**Read this first.**');
  out.push('');
  out.push('- Every saved position is a simulation result, under the assumptions of `summary.md` and `portfolio.md`: the keeper, RPCs, NEAR and the MPC network all work, with a fixed delay D. The helper in `docs/SPEC.md` section 9 is modelled from its spec, and the replayed keeper sends without quoting first, which the built keeper does not (assumption 28).');
  out.push('- Each unwind is priced from a real Uniswap v3 QuoterV2 quote at its landing block, read from an archive node, against AaveOracle in the same block. Between fixed ladder amounts the price is interpolated on a straight line, which overstates the cost where it errs, apart from rounding of a token\'s smallest unit on sales of a few dollars. Validation below gives the error.');
  out.push('- The swap is assumed to execute at the quoted price. Other traders in the same crash, and other Levee positions selling the same asset in the same block, are not modelled: each unwind sees the pool as it was.');
  out.push('- Collateral mode needs no cash. Its comparison with the same USDC repaid upfront is about protection only: upfront needs that USDC in hand.');
  out.push('- No crash frequency is estimated from two windows.');
  out.push('');
  out.push(`Unless stated: T ${b.trigger.toFixed(2)}, G ${b.target.toFixed(2)}, D ${b.delaySec} s, cooldown ${b.cooldownSec} s, the cheapest usable fee tier at each unwind, and ${r.rules.gasPerUnwind.toLocaleString('en-US')} gas per unwind sent. Both caps, ${caps.join(' and ')} bps, are shown side by side.`);
  out.push('');

  // The answer.
  out.push('## Against doing nothing, the reserve and an upfront repay');
  out.push('');
  out.push('Every native USDC borrower on both pools, as in `portfolio.md`. Doing nothing is the real outcome: every liquidated member was liquidated and paid the bonus. The reserve and upfront columns are read from `results/portfolio.json` at R 30% of debt; "capped" counts a landed repay only up to the USDC debt still on the path, as collateral mode does. Net is bonus avoided minus swap cost minus gas, over every member, liquidated or not.');
  out.push('');
  out.push(
    table(
      ['Period', 'Members', 'Liquidated', 'Saved: collateral, 100 bps', '300 bps', 'Reserve R 30%, capped', 'Upfront R 30%', 'Bonus at risk', 'Avoided: collateral, 100 bps', '300 bps', 'Reserve, capped', 'Upfront', 'Swap cost, 100 / 300 bps', 'Gas, 100 / 300 bps', 'Net, 100 / 300 bps'],
      periods.map((period) => {
        const a = row(period, b.trigger, caps[0]!);
        const z = row(period, b.trigger, caps[1]!);
        const c = cmp(period, b.trigger);
        return [
          label(period),
          a.members,
          a.liquidated,
          `${a.saved} (${pct(a.saved, a.liquidated)})`,
          `${z.saved} (${pct(z.saved, z.liquidated)})`,
          `${c.reserve.savedCapped}`,
          `${c.upfront.saved}`,
          usd(a.bonusAtRisk),
          usd(a.bonusAvoided),
          usd(z.bonusAvoided),
          usd(c.reserve.bonusAvoidedCapped ?? NaN),
          usd(c.upfront.bonusAvoided),
          `${usd(a.swapCost)} / ${usd(z.swapCost)}`,
          `${usd(a.gas)} / ${usd(z.gas)}`,
          `${usd(a.net)} / ${usd(z.net)}`,
        ];
      }),
    ),
  );
  out.push('');
  out.push('Gas falls mostly on reverted unwinds, which the keeper here sends again and again (README, assumption 28). With no gas on reverts, which bounds what a keeper that checked a quote before sending could save:');
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Unwinds sent', 'Landed', 'Reverted', 'Gas', 'Of that, on reverted unwinds', 'Gas per landed unwind', 'Net', 'Net with no gas on reverts'],
      periods.flatMap((period) =>
        caps.map((cap) => {
          const a = row(period, b.trigger, cap);
          return [label(period), `${cap}`, a.sent, a.landed, reverted(a), usd(a.gas), usd(a.gasReverted), usd(a.landed ? (a.gas - a.gasReverted) / a.landed : 0), usd(a.net), usd(a.net + a.gasReverted)];
        }),
      ),
    ),
  );
  out.push('');
  out.push('Some unwinds sold into a pool that had not caught up with a falling oracle and paid more than it, which shows as a negative swap cost. An arbitrageur would usually get there first, so this table also counts every unwind at no better than the oracle:');
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Swap cost', 'Swap cost, no unwind better than the oracle', 'Net', 'Net, no unwind better than the oracle'],
      periods.flatMap((period) =>
        caps.map((cap) => {
          const a = row(period, b.trigger, cap);
          return [label(period), `${cap}`, usd(a.swapCost), usd(a.swapCostPositive), usd(a.net), usd(a.net - (a.swapCostPositive - a.swapCost))];
        }),
      ),
    ),
  );
  out.push('');
  out.push('In one line per period, at T 1.20:');
  out.push('');
  for (const period of periods) {
    for (const cap of caps) {
      const a = row(period, b.trigger, cap);
      out.push(
        `- ${label(period)}, ${cap} bps cap: across ${a.members.toLocaleString('en-US')} borrowers, collateral mode avoided ${usd(a.bonusAvoided)} of liquidation bonus and paid ${usd(a.swapCost)} in swap costs, of which ${usd(a.swapCostSurvivors)} on borrowers who were not liquidated anyway, and ${usd(a.gas)} in gas, of which ${usd(a.gasReverted)} on unwinds that reverted.`,
      );
    }
  }
  out.push('');

  // Triggers.
  out.push('## By trigger');
  out.push('');
  out.push('Every member, both chains. "Crossed T", "Liquidated" and "False alarms" have the `portfolio.md` meaning: members armed above T whose HF later fell below it; of those, liquidated; and of those not liquidated, never below HF 1. Members armed below T unwind at once, which is an upfront deleverage, not a rescue.');
  out.push('');
  for (const period of periods) {
    out.push(`### ${label(period)}`);
    out.push('');
    out.push(
      table(
        ['T', 'Cap', 'Members', 'Armed below T', 'Crossed T', 'False alarms', 'Liquidated', 'Saved', 'Saved: reserve R 30%', 'Saved: upfront R 30%', 'Bonus avoided', 'Unwinds landed', 'Reverted', 'Swap cost', 'Gas', 'Net', 'Net per $1,000 of debt'],
        GRID.triggers.flatMap((t) =>
          caps.map((cap) => {
            const a = row(period, t, cap);
            const c = cmp(period, t);
            return [t.toFixed(2), `${cap}`, a.members, a.armedBelow, a.crossed, a.falseAlarms, a.liquidated, a.saved, c.reserve.saved, c.upfront.saved, usd(a.bonusAvoided), a.landed, reverted(a), usd(a.swapCost), usd(a.gas), usd(a.net), per1000(a.net, a.debtAtArming)];
          }),
        ),
      ),
    );
    out.push('');
  }
  out.push('The reserve column here is the pre-registered, uncapped count from `portfolio.md`, which at T 1.20 is a few positions above the capped one in the table at the top.');
  out.push('');

  // Size.
  out.push('## Costs and net benefit by size');
  out.push('');
  out.push('Debt at arming, T 1.20. Net is bonus avoided minus swap cost minus gas. Per position divides by every member in the band.');
  out.push('');
  for (const cap of caps) {
    out.push(`### ${cap} bps cap`);
    out.push('');
    out.push(
      table(
        ['Period', 'Debt at arming', 'Members', 'No usable pool', 'Liquidated', 'Saved', 'Bonus avoided', 'Swap cost', 'Gas', 'Net', 'Net per position', 'Net per $1,000 of debt'],
        r.bySize
          .filter((s) => s.slippageBps === cap)
          .map((s) => [label(s.period), s.bucket.replace(/^\d\. /, ''), s.members, s.noPool, s.liquidated, s.saved, usd(s.bonusAvoided), usd(s.swapCost), usd(s.gas), usd(s.net), usd(s.members ? s.net / s.members : 0), per1000(s.net, s.debtAtArming)]),
      ),
    );
    out.push('');
  }

  // False alarms.
  out.push('## False alarms');
  out.push('');
  out.push('Members armed above T that crossed it, were not liquidated, and never had HF below 1: they would have survived anyway. What collateral mode cost them: swap cost, gas, and collateral sold, which is deleveraging they did not need. "Share of their collateral" is collateral sold over their collateral at arming, at the oracle.');
  out.push('');
  out.push(
    table(
      ['Period', 'T', 'Cap', 'False alarms', 'With an unwind landed', 'Swap cost', 'Gas', 'Per false alarm', 'Collateral sold', 'Share of their collateral', 'Median per borrower with an unwind', 'p90'],
      periods.flatMap((period) =>
        GRID.triggers.flatMap((t) =>
          caps.map((cap) => {
            const a = row(period, t, cap);
            const s = t === b.trigger ? r.falseAlarmShares.find((x) => x.period === period && x.slippageBps === cap)! : null;
            return [
              label(period),
              t.toFixed(2),
              `${cap}`,
              a.falseAlarms,
              a.falseAlarmsWithUnwind,
              usd(a.swapCostFalseAlarms),
              usd(a.gasFalseAlarms),
              usd(a.falseAlarms ? (a.swapCostFalseAlarms + a.gasFalseAlarms) / a.falseAlarms : 0),
              usd(a.soldFalseAlarms),
              pct(a.soldFalseAlarms, a.collateralFalseAlarms, 2),
              s ? share(s.median) : '',
              s ? share(s.p90) : '',
            ];
          }),
        ),
      ),
    ),
  );
  out.push('');
  out.push('Members not liquidated in reality include more than false alarms: members armed below T, which unwind at once, and members whose HF fell below 1 with no liquidation. Their swap cost is in "on borrowers who were not liquidated anyway" in the lines above.');
  out.push('');

  // Calm.
  out.push('## The calm period, per member');
  out.push('');
  out.push(`${label(CALM_ID)}, 30 days. Members armed above T only, so an unwind at arming does not count. Swap cost and gas are per member armed above T over the 30 days; collateral sold is a share of what those members held at arming.`);
  out.push('');
  out.push(
    table(
      ['T', 'Cap', 'Members armed above T', 'Crossed T', 'Liquidated', 'Swap cost and gas per member', 'Per member that crossed', 'Collateral sold per member', 'As a share of their collateral'],
      GRID.triggers.flatMap((t) =>
        caps.map((cap) => {
          const a = row(CALM_ID, t, cap);
          const above = a.members - a.armedBelow;
          const cost = a.swapCost + a.gas - a.swapCostArmedBelow - a.gasArmedBelow;
          const sold = a.sold - a.soldArmedBelow;
          return [t.toFixed(2), `${cap}`, above, a.crossed, a.crossedLiquidated, usd(above ? cost / above : 0), usd(a.crossed ? cost / a.crossed : 0), usd(above ? sold / above : 0), pct(sold, a.collateralArmedAbove, 2)];
        }),
      ),
    ),
  );
  out.push('');

  // Misses.
  out.push('## Why liquidated positions were not saved');
  out.push('');
  out.push('T 1.20, every liquidated member. `no_pool`: no collateral with a usable pool. `slippage_cap`: an unwind reverted, on the cap or because no tier could fill it, before the position failed. `under_minimum`: HF crossed T, but every unwind the rule asked for was under the $1 floor, which is mostly dust. The rest have the `summary.md` meaning, with `collateral_exhausted` in place of `reserve_empty`.');
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Liquidated', ...REASONS.map((x) => `\`${x}\``), 'Bonus at risk, no usable pool'],
      periods.flatMap((period) =>
        caps.map((cap) => {
          const a = row(period, b.trigger, cap);
          return [label(period), `${cap}`, a.liquidated, ...REASONS.map((x) => a.reasons[x]), usd(a.bonusAtRiskNoPool)];
        }),
      ),
    ),
  );
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Unwinds sent', 'Landed', 'Reverted on the cap', 'Reverted, no tier could fill it', 'Still in flight at the end'],
      periods.flatMap((period) => caps.map((cap) => {
        const a = row(period, b.trigger, cap);
        return [label(period), `${cap}`, a.sent, a.landed, a.revertedCap, a.revertedLiquidity, a.unresolved];
      })),
    ),
  );
  out.push('');

  // Pools.
  out.push('## Which collateral is sold, and no_pool');
  out.push('');
  out.push(`A tier is usable if a quote for ${r.rules.probeUsdc.toLocaleString('en-US')} USDC out at the period's first block is within ${r.rules.probeMaxBps} bps of AaveOracle. The configured tier holds the most USDC.`);
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', 'Usable assets: tiers, configured tier and its USDC'],
      r.pools.map((p) => [label(p.period), p.chain, p.assets.map((a) => `${a.symbol} ${a.tiers.join('/')} (${a.configuredFee}, ${usd(a.usdcInConfigured)})`).join('; ')]),
    ),
  );
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', 'Members', 'No usable pool', 'Debt at arming, no usable pool', 'Liquidated, no usable pool', 'Bonus at risk, no usable pool'],
      periods.flatMap((period) =>
        (['arbitrum', 'base'] as const).map((chain) => {
          const a = row(period, b.trigger, caps[0]!, 'cheapest', chain);
          const sold = r.soldAssets.filter((s) => s.period === period && s.chain === chain).reduce((sum, s) => sum + s.debtAtArming, 0);
          return [label(period), chain, a.members, `${a.noPool} (${pct(a.noPool, a.members)})`, `${usd(a.debtAtArming - sold)} of ${usd(a.debtAtArming)}`, a.liquidatedNoPool, usd(a.bonusAtRiskNoPool)];
        }),
      ),
    ),
  );
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', 'Sold asset: members, debt at arming'],
      periods.flatMap((period) =>
        (['arbitrum', 'base'] as const).map((chain) => [
          label(period),
          chain,
          r.soldAssets
            .filter((s) => s.period === period && s.chain === chain)
            .map((s) => `${s.symbol} ${s.members}, ${usd(s.debtAtArming)}`)
            .join('; '),
        ]),
      ),
    ),
  );
  out.push('');

  // Swap cost.
  out.push('## What a swap cost');
  out.push('');
  out.push('Landed unwinds at T 1.20, cost against AaveOracle at the landing block, in bps of the USDC received. Negative means the pool paid more than the oracle. "Gap" is the part due to the pool price before the swap differing from the oracle; the rest is the fee and price impact.');
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Landed', 'p10', 'Median', 'p90', 'p99', 'Max', 'Dollar-weighted', 'Share of cost from the gap', 'Landed by tier'],
      r.costs.map((d) => [
        label(d.period),
        `${d.slippageBps}`,
        d.landed,
        bps(d.p10),
        bps(d.p50),
        bps(d.p90),
        bps(d.p99),
        bps(d.max),
        bps(d.weightedBps),
        share(d.gapShare),
        Object.entries(d.byFee)
          .sort((x, y) => Number(x[0]) - Number(y[0]))
          .map(([fee, n]) => `${fee}: ${n}`)
          .join(', '),
      ]),
    ),
  );
  out.push('');
  out.push('Fixing the tier, as the spec\'s `pool_fee` does, instead of taking the cheapest at each unwind:');
  out.push('');
  out.push(
    table(
      ['Period', 'Cap', 'Saved: cheapest', 'Configured tier', 'Bonus avoided: cheapest', 'Configured', 'Swap cost: cheapest', 'Configured', 'Reverted: cheapest', 'Configured'],
      periods.flatMap((period) =>
        caps.map((cap) => {
          const a = row(period, b.trigger, cap);
          const f = row(period, b.trigger, cap, 'configured');
          return [label(period), `${cap}`, a.saved, f.saved, usd(a.bonusAvoided), usd(f.bonusAvoided), usd(a.swapCost), usd(f.swapCost), reverted(a), reverted(f)];
        }),
      ),
    ),
  );
  out.push('');

  // Headline grid.
  out.push('## Liquidated positions in the headline set');
  out.push('');
  out.push(`The ${r.headlineUpfront.positions.toLocaleString('en-US')} in-scope positions of \`summary.md\`, both crash windows, on their committed paths. Reserve mode is \`summary.json\` at R 30%. Each cell reads: collateral saved at 100 bps / 300 bps / reserve R 30%.`);
  out.push('');
  for (const target of GRID.targets) {
    out.push(`G = ${target.toFixed(2)}`);
    out.push('');
    out.push(
      table(
        ['T \\ D', ...GRID.delaysSec.map((d) => `${d} s`)],
        GRID.triggers
          .filter((t) => t < target)
          .map((t) => [
            t.toFixed(2),
            ...GRID.delaysSec.map((d) => {
              const lo = gridRow('all', t, target, d, caps[0]!);
              const hi = gridRow('all', t, target, d, caps[1]!);
              const res = r.headlineReserve.find((x) => x.trigger === t && x.target === target && x.delaySec === d);
              return `${lo?.saved ?? ''} / ${hi?.saved ?? ''} / ${res?.saved ?? ''}`;
            }),
          ]),
      ),
    );
    out.push('');
  }
  const headLo = gridRow('all', b.trigger, b.target, b.delaySec, caps[0]!)!;
  const headHi = gridRow('all', b.trigger, b.target, b.delaySec, caps[1]!)!;
  const headRes = r.headlineReserve.find((x) => x.trigger === b.trigger && x.target === b.target && x.delaySec === b.delaySec)!;
  out.push(
    `At T 1.20, G 1.50, D 60 s: collateral mode saved ${headLo.saved} (100 bps) and ${headHi.saved} (300 bps) of ${headLo.members}, against ${headRes.saved} for the reserve at R 30% and ${r.headlineUpfront.saved} for the same USDC repaid at arming. Bonus avoided: ${usd(headLo.bonusAvoided)} and ${usd(headHi.bonusAvoided)}, against ${usd(headRes.bonusAvoided)} and ${usd(r.headlineUpfront.bonusAvoided)}, of ${usd(r.headlineUpfront.bonusAtRisk)} at risk. Swap cost ${usd(headLo.swapCost)} and ${usd(headHi.swapCost)}; gas ${usd(headLo.gas)} and ${usd(headHi.gas)}.`,
  );
  out.push('');
  out.push(
    table(
      ['Window', 'Cap', 'Positions', 'Armed below T', 'Saved', 'Saved, armed above T', 'Bonus avoided', 'Of that, armed above T', ...REASONS.filter((x) => x !== 'saved').map((x) => `\`${x}\``)],
      ['all', ...crashes].flatMap((w) =>
        caps.map((cap) => {
          const g = gridRow(w, b.trigger, b.target, b.delaySec, cap)!;
          return [w === 'all' ? 'both' : label(w), `${cap}`, g.members, g.armedBelow, g.saved, g.saved - g.savedArmedBelow, usd(g.bonusAvoided), usd(g.bonusAvoidedArmedAbove), ...REASONS.filter((x) => x !== 'saved').map((x) => g.reasons[x])];
        }),
      ),
    ),
  );
  out.push('');
  out.push('Cooldown, at T 1.20, G 1.50, D 60 s:');
  out.push('');
  out.push(
    table(
      ['Cooldown', 'Saved, 100 bps', 'Saved, 300 bps', 'Unwinds sent, 100 bps', 'Unwinds sent, 300 bps', '`follow_up_too_slow`, 100 bps', '300 bps'],
      [0, 10, 60, 300].map((c) => {
        const lo = gridRow('all', b.trigger, b.target, b.delaySec, caps[0]!, c)!;
        const hi = gridRow('all', b.trigger, b.target, b.delaySec, caps[1]!, c)!;
        return [`${c} s`, lo.saved, hi.saved, lo.sent, hi.sent, lo.reasons.follow_up_too_slow, hi.reasons.follow_up_too_slow];
      }),
    ),
  );
  out.push('');

  // Validation.
  out.push('## Validation');
  out.push('');
  out.push(
    table(
      ['Check', 'Chain', 'n', 'Result'],
      [
        ...r.validation.landing.map((v) => [
          'Landing block header time minus landing time, at every quoted unwind of the headline cell (100 bps)',
          v.chain,
          v.n,
          `median ${v.median} s, p95 ${v.p95} s, range ${v.min} to ${v.max} s, ${share(v.within2s)} within 2 s`,
        ]),
        ...r.validation.oracle.map((v) => ['AaveOracle price of the sold asset read with the quotes, against the committed price files', v.chain, v.n, `${v.exact} identical, ${v.within1bp} within 1 bp, worst ${bps(v.maxBps)} bps`]),
      ],
    ),
  );
  out.push('');
  const network = r.validation.network as null | { rows?: Array<{ check: string; chain: string; n: number; result: string }> };
  if (network?.rows) {
    out.push(table(['Check', 'Chain', 'n', 'Result'], network.rows.map((x) => [x.check.replace(/\|/g, '\\|'), x.chain, x.n, x.result.replace(/\|/g, '\\|')])));
    out.push('');
  }

  // Full rows by chain.
  out.push('## Full table by chain');
  out.push('');
  out.push(
    table(
      ['Period', 'Chain', 'T', 'Cap', 'Tier', 'Members', 'No usable pool', 'Liquidated', 'Saved', 'Bonus avoided', 'Sent', 'Landed', 'Reverted', 'Repaid', 'Collateral sold', 'Swap cost', 'Gas', 'Net'],
      r.population
        .filter((x) => x.chain !== 'all')
        .map((x) => [label(x.period), x.chain, x.trigger.toFixed(2), `${x.slippageBps}`, x.tier, x.members, x.noPool, x.liquidated, x.saved, usd(x.bonusAvoided), x.sent, x.landed, reverted(x), usd(x.repaid), usd(x.sold), usd(x.swapCost), usd(x.gas), usd(x.net)]),
    ),
  );
  out.push('');
  return out.join('\n');
}
